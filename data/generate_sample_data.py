"""Synthetic sample data with a fixed seed (design.md section 20).

Five daily price series over ~1.260 business days (five years), with
heterogeneous annual means (4 % - 14 %) and volatilities (12 % - 38 %), a target
correlation matrix with pairwise correlations between 0,15 and 0,65 generated by
Cholesky, and ``P_t = P_0 * exp(sum r)`` with ``P_0`` in {25, 48, 120, 310, 7} so
the integer-rounding path of the purchase balance is exercised against very
different price levels.

The app consumes ``generate_prices`` in memory and writes nothing to disk;
``write_sample_files`` only writes into temporary directories used by the tests.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd

from core.rng import child_rng

__all__ = ['ASSET_NAMES', 'N_DAYS', 'generate_prices', 'write_sample_files']

ASSET_NAMES = ('ACTIVO_A', 'ACTIVO_B', 'ACTIVO_C', 'ACTIVO_D', 'ACTIVO_E')
N_DAYS = 1260
START_DATE = '2019-01-02'
TRADING_DAYS = 252

MU_ANNUAL = np.array([0.04, 0.07, 0.09, 0.115, 0.14])
VOL_ANNUAL = np.array([0.12, 0.18, 0.24, 0.30, 0.38])
INITIAL_PRICES = np.array([25.0, 48.0, 120.0, 310.0, 7.0])
TARGET_CORRELATION = np.array([
    [1.00, 0.65, 0.45, 0.25, 0.15],
    [0.65, 1.00, 0.55, 0.30, 0.20],
    [0.45, 0.55, 1.00, 0.35, 0.25],
    [0.25, 0.30, 0.35, 1.00, 0.40],
    [0.15, 0.20, 0.25, 0.40, 1.00],
])


def generate_prices(seed: int = 42) -> pd.DataFrame:
    """Return a (1260, 5) price frame indexed by business days.

    Deterministic: two calls with the same seed produce bit-identical values,
    because the only generator is ``core.rng.child_rng(seed, 'sample_data')``.
    """
    rng = child_rng(seed, 'sample_data')
    dates = pd.bdate_range(start=START_DATE, periods=N_DAYS)

    mu_daily = MU_ANNUAL / TRADING_DAYS
    sigma_daily = VOL_ANNUAL / np.sqrt(TRADING_DAYS)
    factor = np.linalg.cholesky(TARGET_CORRELATION)

    shocks = rng.standard_normal((N_DAYS, len(ASSET_NAMES)))
    correlated = shocks @ factor.T
    log_returns = mu_daily + correlated * sigma_daily
    prices = INITIAL_PRICES * np.exp(np.cumsum(log_returns, axis=0))
    return pd.DataFrame(prices, index=dates, columns=list(ASSET_NAMES))


def _es_frame(dates: pd.DatetimeIndex, values: np.ndarray) -> pd.DataFrame:
    """Build the es-ES flavour of a single-asset frame: dd/mm/yyyy and decimal comma."""
    formatted = [f'{v:,.2f}'.replace(',', '\x00').replace('.', ',').replace('\x00', '.')
                 for v in values]
    return pd.DataFrame({'Fecha': dates.strftime('%d/%m/%Y'),
                         'Cierre ajustado': formatted})


def write_sample_files(directory: str | Path) -> dict:
    """Write the sample material for both loader paths and return the paths written.

    Keys: 'excel' (one wide workbook, Format A), 'csv' (five single-asset files,
    Format B) and 'csv_es' (the same five with ';' separator, decimal comma and
    dd/mm/yyyy dates).
    """
    target = Path(directory)
    target.mkdir(parents=True, exist_ok=True)
    prices = generate_prices()

    wide = prices.copy()
    wide.index.name = 'Fecha'
    excel_path = target / 'activos_formato_a.xlsx'
    wide.reset_index().to_excel(excel_path, index=False, sheet_name='Precios')

    csv_paths = []
    csv_es_paths = []
    for name in ASSET_NAMES:
        column = prices[name]
        single = pd.DataFrame({'Fecha': prices.index.strftime('%Y-%m-%d'),
                               'Adj Close': column.to_numpy()})
        csv_path = target / f'{name}.csv'
        single.to_csv(csv_path, index=False)
        csv_paths.append(csv_path)

        es_path = target / f'{name}_es.csv'
        _es_frame(prices.index, column.to_numpy()).to_csv(es_path, index=False, sep=';')
        csv_es_paths.append(es_path)

    return {'excel': excel_path, 'csv': csv_paths, 'csv_es': csv_es_paths}
